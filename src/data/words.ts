// Light English lemmatizer: reduce common inflections to a base form present
// in the dictionary (sins→sin, loved→love, giving→give, studies→study…).
function enStem(k: string): string[] {
  const c = [k];
  if (/ies$/.test(k)) c.push(k.slice(0, -3) + 'y');
  if (/es$/.test(k)) c.push(k.slice(0, -2));
  if (/s$/.test(k) && k.length > 3) c.push(k.slice(0, -1));
  if (/ied$/.test(k)) c.push(k.slice(0, -3) + 'y');
  if (/ed$/.test(k)) {
    c.push(k.slice(0, -2), k.slice(0, -1));
    if (k.length > 4 && k[k.length - 3] === k[k.length - 4]) c.push(k.slice(0, -3)); // stopped→stop
  }
  if (/ing$/.test(k)) {
    c.push(k.slice(0, -3), k.slice(0, -3) + 'e'); // giving→giv→give
    if (k.length > 5 && k[k.length - 4] === k[k.length - 5]) c.push(k.slice(0, -4)); // running→run
  }
  if (/er$/.test(k) && k.length > 4) c.push(k.slice(0, -2), k.slice(0, -1)); // closer→close
  if (/est$/.test(k) && k.length > 5) c.push(k.slice(0, -3), k.slice(0, -2)); // greatest→great
  if (/ly$/.test(k) && k.length > 4) c.push(k.slice(0, -2)); // fully→full
  return c;
}

export function lookup(token: string, lang: 'en' | 'ko'): Lookup | null {
  if (lang === 'en') {
    const raw = token.toLowerCase().replace(/[^a-z']/g, '');
    for (const k of enStem(raw)) {
      const e = WORDS.en[k];
      if (e) return { headword: k, def: KODEF[k] || e.ko, defAlt: e.def, trans: e.ko, roman: null, pos: e.pos, lang: 'en' };
    }
    return null;
  }
  const d = WORDS.ko;
  if (d[token]) return mkKo(token, d[token]);
  for (const p of KO_PARTICLES) {
    if (token.length > p.length && token.endsWith(p)) {
      const base = token.slice(0, token.length - p.length);
      if (d[base]) return mkKo(base, d[base]);
    }
  }
  let best: string | null = null;
  for (const k in d) {
    if (k.length >= 2 && token.startsWith(k) && (!best || k.length > best.length)) best = k;
  }
  if (best) return mkKo(best, d[best]);
  for (const k in d) {
    if (k.length >= 2 && token.includes(k)) return mkKo(k, d[k]);
  }
  return null;
}
